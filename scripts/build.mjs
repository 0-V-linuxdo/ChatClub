async function exists(p) {
  try {
    await fs.access(p);
    return true;
  } catch {
    return false;
  }
}

async function copyDir(from, to, skip = () => false) {
  await fs.mkdir(to, { recursive: true });
  for (const entry of await fs.readdir(from, { withFileTypes: true })) {
    const a = path.join(from, entry.name);
    const b = path.join(to, entry.name);
    if (skip(a, entry)) continue;
    if (entry.isDirectory()) await copyDir(a, b, skip);
    else await fs.copyFile(a, b);
  }
}

function gitTimestamp(dir) {
  try {
    const out = execFileSync("git", ["log", "-1", "--format=%ct", "--", dir], { cwd: root, encoding: "utf8" }).trim();
    return out ? Number(out) * 1000 : null;
  } catch {
    return null;
  }
}

async function buildIcons() {
  const iconDir = path.join(root, "node_modules", "lucide-static", "icons");
  const out = {};
  for (const [name, file] of Object.entries(ICONS)) {
    const svg = await fs.readFile(path.join(iconDir, `${file}.svg`), "utf8");
    const inner = svg.slice(svg.indexOf(">", svg.indexOf("<svg")) + 1, svg.lastIndexOf("</svg>")).replace(/\s+/g, " ").trim();
    out[name] = inner;
  }
  const license = (await fs.readFile(path.join(root, "node_modules", "lucide-static", "LICENSE"), "utf8")).trim();
  return `// Generated by scripts/build.mjs from lucide-static. Do not edit.\n/*\n${license}\n*/\nexport const ICON_PATHS = ${JSON.stringify(out, null, 0)};\n`;
}

// Content bundles are classic scripts: `/* @include lib/<file>.js */` pastes a shared ES module in place,
// with its `export` keywords removed (the module must not import anything).
async function inlineIncludes(code) {
  const re = /\/\* @include (lib\/[\w.-]+\.js) \*\//g;
  const parts = [];
  let last = 0;
  for (const m of code.matchAll(re)) {
    parts.push(code.slice(last, m.index));
    const lib = await fs.readFile(path.join(src, m[1]), "utf8");
    if (/^\s*import\s/m.test(lib)) throw new Error(`${m[1]} cannot be included in a content bundle: it imports modules`);
    parts.push(lib.replace(/^export\s+(?=(async\s+)?(function|const|let|class)\b)/gm, ""));
    last = m.index + m[0].length;
  }
  parts.push(code.slice(last));
  return parts.join("");
}

async function main() {
  await fs.rm(outDir, { recursive: true, force: true });
  const pluginRoot = path.join(src, "plugins");
  const order = JSON.parse(await fs.readFile(path.join(pluginRoot, "order.json"), "utf8"));
  const folders = (await fs.readdir(pluginRoot, { withFileTypes: true })).filter((e) => e.isDirectory()).map((e) => e.name);
  const devFolders = (await exists(path.join(pluginRoot, "dev")))
    ? (await fs.readdir(path.join(pluginRoot, "dev"), { withFileTypes: true })).filter((e) => e.isDirectory()).map((e) => `dev/${e.name}`)
    : [];
  const all = [...order, ...(release ? [] : devFolders)];
  for (const f of folders) if (f !== "dev" && !order.includes(f)) throw new Error(`Plugin folder "${f}" is missing from plugins/order.json`);

  await copyDir(src, outDir, (abs) => release && abs.startsWith(path.join(pluginRoot, "dev")));
  const iconsModule = await buildIcons();
  await fs.writeFile(path.join(outDir, "lib", "icons.generated.js"), iconsModule);
  await fs.writeFile(path.join(src, "lib", "icons.generated.js"), iconsModule);

  // Content runtime is prepended to every capability bundle so each file is self-contained.
  const runtime = await fs.readFile(path.join(src, "content", "runtime.js"), "utf8");
  const appImports = [];
  const bgImports = [];
  const updatedAt = {};
  const seenCaps = new Set();
  await fs.mkdir(path.join(outDir, "content"), { recursive: true });
  for (const [i, folder] of all.entries()) {
    const indexPath = path.join(pluginRoot, folder, "index.js");
    if (!(await exists(indexPath))) throw new Error(`Missing ${indexPath}`);
    const mod = await import(pathToFileURL(indexPath).href);
    const def = mod.default;
    if (!def?.name) throw new Error(`${folder}/index.js must default-export a plugin definition`);
    appImports.push(`import p${i} from "./${folder}/index.js";`);
    if (await exists(path.join(pluginRoot, folder, "background.js"))) {
      bgImports.push({ i, folder, name: def.name });
    }
    const ts = gitTimestamp(path.join("src", "plugins", folder));
    if (ts) updatedAt[def.name] = ts;
    for (const cap of def.content ?? []) {
      if (seenCaps.has(cap.id)) throw new Error(`Duplicate content capability id "${cap.id}"`);
      seenCaps.add(cap.id);
      const bundle = await inlineIncludes(await fs.readFile(path.join(pluginRoot, folder, cap.bundle), "utf8"));
      const prefix = cap.world === "MAIN" ? "" : `${runtime}\n`;
      await fs.writeFile(path.join(outDir, "content", `${cap.id}.js`), `${prefix};(() => {\n${bundle}\n})();\n`);
    }
  }
  const list = `export const PLUGINS = [${all.map((_, i) => `p${i}`).join(", ")}];`;
  const stamp = `const UPDATED_AT = ${JSON.stringify(updatedAt)};\nfor (const p of PLUGINS) if (p.updatedAt === undefined && UPDATED_AT[p.name]) p.updatedAt = UPDATED_AT[p.name];`;
  await fs.writeFile(
    path.join(outDir, "plugins", "all.app.js"),
    `// Generated by scripts/build.mjs.\n${appImports.join("\n")}\n${list}\n${stamp}\n`,
  );
  await fs.writeFile(
    path.join(outDir, "plugins", "all.background.js"),
    `// Generated by scripts/build.mjs. Background parts are static imports (no dynamic import in service workers).\n` +
      `import { PLUGINS } from "./all.app.js";\n` +
      bgImports.map(({ i, folder }) => `import b${i} from "./${folder}/background.js";`).join("\n") +
      `\nconst PARTS = { ${bgImports.map(({ i, name }) => `${JSON.stringify(name)}: b${i}`).join(", ")} };\n` +
      `for (const p of PLUGINS) if (PARTS[p.name]) p.background = PARTS[p.name];\nexport { PLUGINS };\n`,
  );

  const pkg = JSON.parse(await fs.readFile(path.join(root, "package.json"), "utf8"));
  const buildInfo = { version: pkg.version, isDev: !release, builtAt: Date.now() };
  await fs.writeFile(path.join(outDir, "build-info.js"), `export const BUILD = ${JSON.stringify(buildInfo)};\n`);
  const manifestPath = path.join(outDir, "manifest.json");
  const manifest = JSON.parse(await fs.readFile(manifestPath, "utf8"));
  manifest.version = pkg.version;
  await fs.writeFile(manifestPath, JSON.stringify(manifest, null, 2));
  console.log(`Built ${all.length} plugins into ${path.relative(root, outDir)}${release ? " (release)" : ""}`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
